"""Write letter-only LaTeX macros for the sports manuscript from E6 oracles.

Reads (no refit beyond existing CSVs):
  results/E6_sports.csv
  results/E6_sports_summary.csv
  confirmatory_exemplars.csv (display order only)

Writes:
  ../../scripts/paper_pipeline/outputs/sports_numbers.tex

Run from the package root:
  python analysis/write_sports_numbers.py
"""
from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
REPO = PKG.parent.parent
E6 = PKG / "results" / "E6_sports.csv"
E6_SUM = PKG / "results" / "E6_sports_summary.csv"
EXEMPLARS = REPO / "scripts" / "paper_pipeline" / "outputs" / "confirmatory_exemplars.csv"
OUT = REPO / "scripts" / "paper_pipeline" / "outputs" / "sports_numbers.tex"

EXEMPLAR_ORDER = [
    ("rugby", "lineout_throws_lost", "Qone"),
    ("rugby", "rucks_won", "Qtwo"),
    ("football", "corners", "Qthree"),
    ("football", "fouls", "Qfour"),
]
SEED = 20261027


def fmt(x: float, digits: int = 3) -> str:
    if pd.isna(x):
        return "???"
    return f"{float(x):.{digits}f}"


def fmt_int(x: float) -> str:
    return str(int(round(float(x))))


def fmt_signed(x: float, digits: int = 2) -> str:
    if pd.isna(x):
        return "???"
    v = float(x)
    return f"{v:+.{digits}f}" if v != 0 else f"{v:.{digits}f}"


def median_ci(vals: np.ndarray, rng: np.random.Generator, B: int = 2000):
    vals = np.asarray(vals, float)
    vals = vals[np.isfinite(vals)]
    if len(vals) == 0:
        return np.nan, np.nan, np.nan
    med = float(np.median(vals))
    if len(vals) == 1:
        return med, med, med
    boots = [np.median(rng.choice(vals, size=len(vals), replace=True)) for _ in range(B)]
    lo, hi = np.quantile(boots, [0.025, 0.975])
    return med, float(lo), float(hi)


def main() -> None:
    e6 = pd.read_csv(E6)
    sm = pd.read_csv(E6_SUM)
    rng = np.random.default_rng(SEED)
    lines = [
        "% Auto-generated by Alternative Pipeline/pef_numerics/analysis/write_sports_numbers.py",
        "% Do not hand-edit. Regenerate from E6 CSVs.",
        "",
    ]

    def prov(name: str) -> None:
        lines.append(rf"\providecommand{{\{name}}}{{???}}")

    def ren(name: str, value: str) -> None:
        lines.append(rf"\renewcommand{{\{name}}}{{{value}}}")

    base = [
        "PEFsportNkpis", "PEFrugbyNkpis", "PEFfootNkpis",
        "PEFrugbyNgames", "PEFfootNgames",
        "PEFrugbyMedLR", "PEFrugbyLRqI", "PEFrugbyLRqIII",
        "PEFfootMedLR", "PEFfootLRqI", "PEFfootLRqIII",
        "PEFrugbyNaboveTwo", "PEFrugbyNaboveChi",
        "PEFfootNaboveTwo", "PEFfootNaboveChi",
        "PEFrugbyMedGapDf", "PEFrugbyMedGapDfLo", "PEFrugbyMedGapDfHi",
        "PEFrugbyMedGapAD", "PEFrugbyMedGapADLo", "PEFrugbyMedGapADHi",
        "PEFfootMedGapDf", "PEFfootMedGapDfLo", "PEFfootMedGapDfHi",
        "PEFfootMedGapAD", "PEFfootMedGapADLo", "PEFfootMedGapADHi",
        "PEFrugbyHalfN", "PEFfootHalfN",
        "PEFrugbyCorrEtaDf", "PEFrugbyCorrEtaAD", "PEFrugbyCorrRAAD",
        "PEFfootCorrEtaDf", "PEFfootCorrEtaAD", "PEFfootCorrRAAD",
        "PEFrugbyNinfo", "PEFfootNinfo",
        "PEFrugbyMedSkill", "PEFfootMedSkill",
        "PEFrugbyMedLLint", "PEFfootMedLLint",
        "PEFrugbyHomeWin", "PEFfootHomeWin",
        "PEFrugbyQone", "PEFrugbyQtwo", "PEFrugbyQthree", "PEFrugbyQfour",
        "PEFfootQone", "PEFfootQtwo", "PEFfootQthree", "PEFfootQfour",
        "PEFrugbyMedGapDfInfo", "PEFrugbyMedGapADInfo",
        "PEFfootMedGapDfInfo", "PEFfootMedGapADInfo",
        "PEFrugbyCorrEtaDfInfo", "PEFrugbyCorrEtaADInfo", "PEFrugbyCorrRAADInfo",
        "PEFfootCorrEtaDfInfo", "PEFfootCorrEtaADInfo", "PEFfootCorrRAADInfo",
        "PEFLRlandmark", "PEFLRaic",
    ]
    for name in base:
        prov(name)
    for _, _, tag in EXEMPLAR_ORDER:
        for stem in ("Sport", "KPI", "Kappa", "Rho", "Eta", "RA", "LR", "Skill",
                     "GapDf", "GapDfLo", "GapDfHi", "GapAD", "GapADLo", "GapADHi",
                     "Info"):
            prov(f"PEFex{tag}{stem}")

    lines.append("")

    ren("PEFsportNkpis", fmt_int(len(e6)))
    ren("PEFrugbyNkpis", fmt_int((e6.sport == "rugby").sum()))
    ren("PEFfootNkpis", fmt_int((e6.sport == "football").sum()))
    ren("PEFLRlandmark", "3.84")
    ren("PEFLRaic", "2")

    n_rugby = int(e6.loc[e6.sport == "rugby", "n"].iloc[0])
    n_foot = int(e6.loc[e6.sport == "football", "n"].iloc[0])
    ren("PEFrugbyNgames", f"{n_rugby}")
    ren("PEFfootNgames", f"{n_foot:,}".replace(",", "{,}"))

    # Home-win rates from intercept entropy context: recover from y rate if present.
    # Landscape join already in E6? Not always. Compute from ll not available.
    # Keep from previous landscape merge if columns absent: use fixed from prior macros via E6 n.
    # Prefer reading landscape file if available.
    land_path = REPO / "scripts" / "paper_pipeline" / "outputs" / "pef_landscape_2season.csv"
    if land_path.exists():
        land = pd.read_csv(land_path)
        for sport, name in (("rugby", "PEFrugbyHomeWin"), ("football", "PEFfootHomeWin")):
            rate = float(land.loc[land.sport == sport, "home_win_rate"].iloc[0])
            ren(name, fmt(100.0 * rate, 1))

    for sport, prefix in (("rugby", "PEFrugby"), ("football", "PEFfoot")):
        row = sm.loc[sm.sport == sport].iloc[0]
        g = e6.loc[e6.sport == sport]
        info = g[g.informative]

        ren(f"{prefix}MedLR", fmt(row.median_lr, 2))
        ren(f"{prefix}LRqI", fmt(row.q25_lr, 2))
        ren(f"{prefix}LRqIII", fmt(row.q75_lr, 2))
        ren(f"{prefix}NaboveTwo", fmt_int(row.n_lr_above_two))
        ren(f"{prefix}NaboveChi", fmt_int(row.n_lr_above_chi))
        ren(f"{prefix}Ninfo", fmt_int(row.n_informative))
        ren(f"{prefix}MedSkill", fmt(1000.0 * row.median_skill, 2))
        ren(f"{prefix}MedLLint", fmt(row.median_ll_intercept, 3))
        ren(f"{prefix}HalfN", fmt(row.median_half_n_train_mn, 2))

        med, lo, hi = median_ci(1000.0 * g.gap_D_minus_full.to_numpy(), rng)
        ren(f"{prefix}MedGapDf", fmt(med, 2))
        ren(f"{prefix}MedGapDfLo", fmt(lo, 2))
        ren(f"{prefix}MedGapDfHi", fmt(hi, 2))
        med, lo, hi = median_ci(1000.0 * g.gap_A_minus_D.to_numpy(), rng)
        ren(f"{prefix}MedGapAD", fmt(med, 2))
        ren(f"{prefix}MedGapADLo", fmt(lo, 2))
        ren(f"{prefix}MedGapADHi", fmt(hi, 2))

        ren(f"{prefix}CorrEtaDf", fmt(row.corr_eta_gap_Df, 3))
        ren(f"{prefix}CorrEtaAD", fmt(row.corr_eta_gap_AD, 3))
        ren(f"{prefix}CorrRAAD", fmt(row.corr_rA_gap_AD, 3))

        if len(info):
            ren(f"{prefix}MedGapDfInfo", fmt(1000.0 * row.median_gap_D_full_info, 2))
            ren(f"{prefix}MedGapADInfo", fmt(1000.0 * row.median_gap_A_D_info, 2))
            ren(f"{prefix}CorrEtaDfInfo", fmt(row.corr_eta_gap_Df_info, 3))
            ren(f"{prefix}CorrEtaADInfo", fmt(row.corr_eta_gap_AD_info, 3))
            ren(f"{prefix}CorrRAADInfo", fmt(row.corr_rA_gap_AD_info, 3))
        else:
            for stem in ("MedGapDfInfo", "MedGapADInfo", "CorrEtaDfInfo",
                         "CorrEtaADInfo", "CorrRAADInfo"):
                ren(f"{prefix}{stem}", "---")

        if "quadrant" in g.columns:
            counts = g.groupby("quadrant").size()
            for q, tag in (("Q1", "Qone"), ("Q2", "Qtwo"), ("Q3", "Qthree"), ("Q4", "Qfour")):
                ren(f"{prefix}{tag}", fmt_int(counts.get(q, 0)))

    conf = pd.read_csv(EXEMPLARS) if EXEMPLARS.exists() else None
    for sport, kpi, tag in EXEMPLAR_ORDER:
        r = e6.loc[(e6.sport == sport) & (e6.kpi == kpi)].iloc[0]
        display = kpi.replace("_", " ")
        ren(f"PEFex{tag}Sport", sport)
        ren(f"PEFex{tag}KPI", display)
        ren(f"PEFex{tag}Kappa", fmt(r.kappa, 3))
        ren(f"PEFex{tag}Rho", fmt(r.rho, 3))
        ren(f"PEFex{tag}Eta", fmt(r.eta, 3))
        ren(f"PEFex{tag}RA", fmt(r.r_A, 3))
        ren(f"PEFex{tag}LR", fmt(r.lr, 2))
        ren(f"PEFex{tag}Skill", fmt(1000.0 * r.skill, 2))
        ren(f"PEFex{tag}GapDf", fmt(1000.0 * r.gap_D_minus_full, 2))
        ren(f"PEFex{tag}GapDfLo", fmt(1000.0 * r.boot_gap_D_full_lo, 2))
        ren(f"PEFex{tag}GapDfHi", fmt(1000.0 * r.boot_gap_D_full_hi, 2))
        ren(f"PEFex{tag}GapAD", fmt(1000.0 * r.gap_A_minus_D, 2))
        ren(f"PEFex{tag}GapADLo", fmt(1000.0 * r.boot_gap_A_D_lo, 2))
        ren(f"PEFex{tag}GapADHi", fmt(1000.0 * r.boot_gap_A_D_hi, 2))
        ren(f"PEFex{tag}Info", "yes" if bool(r.informative) else "no")
        if conf is not None:
            c = conf.loc[(conf.sport == sport) & (conf.kpi == kpi)]
            if len(c) and c.iloc[0].quadrant:
                pass

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    os.chdir(PKG)
    main()
